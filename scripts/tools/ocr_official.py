def check_receipt(year, rows, total):
    errs, block, subs = [], [], []
    for r in rows:
        if r[0] == '=':
            s = [sum(x[i] for x in block) for i in range(1, 7)]
            if tuple(s) != r[1:]:
                errs.append(f'{year} 소계 {r[1:]} != 합 {tuple(s)}')
            subs.append(r[1:])
            block = []
            continue
        name, sg, sd, st, ag, ad, at, ratio = r
        if sg + sd != st:
            errs.append(f'{year} {name} 모집 {sg}+{sd}!={st}')
        if ag + ad != at:
            errs.append(f'{year} {name} 접수 {ag}+{ad}!={at}')
        if abs(ag / sg - ratio) > 0.06:
            errs.append(f'{year} {name} 경쟁률 {ag}/{sg}={ag / sg:.2f} vs {ratio}')
        block.append(r)
    t = tuple(sum(s[i] for s in subs) for i in range(6))
    if t != total:
        errs.append(f'{year} 합계 {total} != 소계 합 {t}')
    return errs


