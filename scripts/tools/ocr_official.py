def check_final(year, rows, total, split):
    errs = []
    t = tuple(sum(r[i] for r in rows) for i in (2, 3, 4))
    if t != total:
        errs.append(f'{year} 합계 {total} != 합 {t}')
    sp = (sum(r[4] for r in rows if not r[1]), sum(r[4] for r in rows if r[1]))
    if sp != split:
        errs.append(f'{year} 일반/장애 합격 {sp} != 공고 {split}')
    for name, dis, sel, tk, fin, cut in rows:
        if fin > sel or fin > tk:
            errs.append(f'{year} {name} 합격 {fin} > 선발 {sel} 또는 응시 {tk}')
        if cut is not None and not (100 <= cut <= 200 and fin >= 3):
            errs.append(f'{year} {name} 합격선 {cut} 범위/공개 조건 이상')
    return errs


